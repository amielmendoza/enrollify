export class MainLayoutComponent implements OnInit {
  sidebarOpen = signal(false);

  constructor(public auth: AuthService, public syService: SchoolYearService) {}

  ngOnInit() {
    this.syService.ensureLoaded().subscribe();
  }

  isParent = computed(() => this.auth.userRole() === 'Parent');
  isStudent = computed(() => this.auth.userRole() === 'Student');
  isSuperAdmin = computed(() => this.auth.userRole() === 'SuperAdmin');
  isAdmin = computed(() => this.auth.userRole() === 'Admin');

  userInitials = computed(() => {
    const name = this.auth.user()?.fullName ?? '';
    const parts = name.split(' ');
    if (parts.length >= 2) return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
    return name.substring(0, 2).toUpperCase();
  });
}
